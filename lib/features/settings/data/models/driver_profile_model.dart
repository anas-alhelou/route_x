// lib/features/settings/data/models/driver_profile_model.dart
import '../../domain/entities/driver_profile_entity.dart';

class DriverProfileModel extends DriverProfileEntity {
  const DriverProfileModel({
    required super.name,
    required super.email,
    required super.phone,
    required super.vehicleType,
    required super.vehicleNumber,
    required super.rating,
    required super.isNotificationsEnabled,
    super.photoPath,
    super.loadCapacityKg,
    super.companyName,
    super.companyJoinedAt,
    super.companyCode,
    super.companyLogoUrl,
    super.companyPhone,
    super.companyEmail,
    super.vehicleModel,
    super.vehicleColour,
    super.navigationApp,
    super.avoidTolls,
    super.avoidHighways,
    super.avoidUnpaved,
    super.notifyNewRoutes,
    super.notifyOrderChanges,
    super.notifyDispatchMessages,
    super.notificationSound,
    super.notificationVibrate,
    super.quietHoursEnabled,
    super.quietHoursStartMinutes,
    super.quietHoursEndMinutes,
    super.quietHoursDays,
    super.locationAccess,
  });

  factory DriverProfileModel.fromJson(Map<String, dynamic> json) {
    return DriverProfileModel(
      name: json['name'] as String,
      email: json['email'] as String,
      phone: json['phone'] as String,
      vehicleType: json['vehicle_type'] as String,
      vehicleNumber: json['vehicle_number'] as String,
      rating: (json['rating'] as num).toDouble(),
      isNotificationsEnabled: json['is_notifications_enabled'] as bool,
      photoPath: json['photo_path'] as String?,
      loadCapacityKg: (json['load_capacity_kg'] as num?)?.toInt(),
      companyName: json['company_name'] as String?,
      companyJoinedAt: DateTime.tryParse(json['company_joined_at'] as String? ?? ''),
      companyCode: json['company_code'] as String?,
      companyLogoUrl: json['company_logo_url'] as String?,
      companyPhone: json['company_phone'] as String?,
      companyEmail: json['company_email'] as String?,
      vehicleModel: json['vehicle_model'] as String?,
      vehicleColour: json['vehicle_colour'] as String?,
      navigationApp: json['navigation_app'] as String? ?? 'google_maps',
      avoidTolls: json['avoid_tolls'] as bool? ?? false,
      avoidHighways: json['avoid_highways'] as bool? ?? false,
      avoidUnpaved: json['avoid_unpaved'] as bool? ?? false,
      notifyNewRoutes: json['notify_new_routes'] as bool? ?? true,
      notifyOrderChanges: json['notify_order_changes'] as bool? ?? true,
      notifyDispatchMessages: json['notify_dispatch_messages'] as bool? ?? true,
      notificationSound: json['notification_sound'] as bool? ?? true,
      notificationVibrate: json['notification_vibrate'] as bool? ?? true,
      quietHoursEnabled: json['quiet_hours_enabled'] as bool? ?? false,
      quietHoursStartMinutes: (json['quiet_hours_start_minutes'] as num?)?.toInt() ?? 23 * 60,
      quietHoursEndMinutes: (json['quiet_hours_end_minutes'] as num?)?.toInt() ?? 7 * 60,
      quietHoursDays: (json['quiet_hours_days'] as List?)?.cast<int>() ?? const [1, 2, 3, 4, 5, 6, 7],
      locationAccess: json['location_access'] as String? ?? 'always',
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'name': name,
      'email': email,
      'phone': phone,
      'vehicle_type': vehicleType,
      'vehicle_number': vehicleNumber,
      'rating': rating,
      'is_notifications_enabled': isNotificationsEnabled,
      'photo_path': photoPath,
      'load_capacity_kg': loadCapacityKg,
      'company_name': companyName,
      'company_joined_at': companyJoinedAt?.toIso8601String(),
      'company_code': companyCode,
      'company_logo_url': companyLogoUrl,
      'company_phone': companyPhone,
      'company_email': companyEmail,
      'vehicle_model': vehicleModel,
      'vehicle_colour': vehicleColour,
      'navigation_app': navigationApp,
      'avoid_tolls': avoidTolls,
      'avoid_highways': avoidHighways,
      'avoid_unpaved': avoidUnpaved,
      'notify_new_routes': notifyNewRoutes,
      'notify_order_changes': notifyOrderChanges,
      'notify_dispatch_messages': notifyDispatchMessages,
      'notification_sound': notificationSound,
      'notification_vibrate': notificationVibrate,
      'quiet_hours_enabled': quietHoursEnabled,
      'quiet_hours_start_minutes': quietHoursStartMinutes,
      'quiet_hours_end_minutes': quietHoursEndMinutes,
      'quiet_hours_days': quietHoursDays,
      'location_access': locationAccess,
    };
  }

  factory DriverProfileModel.fromEntity(DriverProfileEntity entity) {
    return DriverProfileModel(
      name: entity.name,
      email: entity.email,
      phone: entity.phone,
      vehicleType: entity.vehicleType,
      vehicleNumber: entity.vehicleNumber,
      rating: entity.rating,
      isNotificationsEnabled: entity.isNotificationsEnabled,
      photoPath: entity.photoPath,
      loadCapacityKg: entity.loadCapacityKg,
      companyName: entity.companyName,
      companyJoinedAt: entity.companyJoinedAt,
      companyCode: entity.companyCode,
      companyLogoUrl: entity.companyLogoUrl,
      companyPhone: entity.companyPhone,
      companyEmail: entity.companyEmail,
      vehicleModel: entity.vehicleModel,
      vehicleColour: entity.vehicleColour,
      navigationApp: entity.navigationApp,
      avoidTolls: entity.avoidTolls,
      avoidHighways: entity.avoidHighways,
      avoidUnpaved: entity.avoidUnpaved,
      notifyNewRoutes: entity.notifyNewRoutes,
      notifyOrderChanges: entity.notifyOrderChanges,
      notifyDispatchMessages: entity.notifyDispatchMessages,
      notificationSound: entity.notificationSound,
      notificationVibrate: entity.notificationVibrate,
      quietHoursEnabled: entity.quietHoursEnabled,
      quietHoursStartMinutes: entity.quietHoursStartMinutes,
      quietHoursEndMinutes: entity.quietHoursEndMinutes,
      quietHoursDays: entity.quietHoursDays,
      locationAccess: entity.locationAccess,
    );
  }
}
